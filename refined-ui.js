/* CampBox Sales Board | Refined Interface
   Presentation only. Existing routes, forms, calculations and Supabase remain intact. */
(function () {
  'use strict';
  var STORE_KEY = 'campbox-sales-appearance-v1';
  var LIGHT = 'cb-apple-light';
  function preference() {
    try { return localStorage.getItem(STORE_KEY) !== 'dark'; }
    catch (_) { return true; }
  }
  function applyAppearance(light) {
    document.documentElement.classList.toggle(LIGHT, light);
    document.documentElement.setAttribute('data-cb-appearance', light ? 'light' : 'dark');
    var button = document.getElementById('cbAppearanceToggle');
    if (button) {
      button.textContent = light ? '☾ Тёмная' : '☀ Светлая';
      button.title = light ? 'Включить тёмную тему' : 'Включить светлую тему';
      button.setAttribute('aria-label', button.title);
      button.setAttribute('aria-pressed', String(!light));
    }
    var themeColor = document.querySelector('meta[name="theme-color"]');
    if (themeColor) themeColor.setAttribute('content', light ? '#f5f5f7' : '#09101f');
  }
  // Read-only preference, no business state is touched.
  applyAppearance(preference());

  var groups = [
    { id: 'sales', label: 'Продажи', pages: ['month', 'funnel', 'contracts'] },
    { id: 'finance', label: 'Финансы', pages: ['finance', 'salary'] },
    { id: 'team', label: 'Команда', pages: ['team', 'summary'] },
    { id: 'reports', label: 'Отчёты', pages: ['analytics', 'report'] }
  ];
  var pageToGroup = {};
  groups.forEach(function (group) {
    group.pages.forEach(function (page) { pageToGroup[page] = group.id; });
  });

  function init() {
    var sidebar = document.querySelector('.v13-sidebar');
    var nav = sidebar && sidebar.querySelector('.v13-nav');
    var topbar = document.querySelector('#mainApp.v13-live>.topbar .actions');
    if (!sidebar || !nav || !topbar || nav.dataset.cbRefined === 'true') return;
    nav.dataset.cbRefined = 'true';

    // Theme is a UI preference only. Toggle cannot save or modify records.
    var appearance = document.createElement('button');
    appearance.type = 'button';
    appearance.className = 'btn cb-appearance';
    appearance.id = 'cbAppearanceToggle';
    appearance.addEventListener('click', function () {
      var next = !document.documentElement.classList.contains(LIGHT);
      try { localStorage.setItem(STORE_KEY, next ? 'light' : 'dark'); } catch (_) {}
      applyAppearance(next);
    });
    topbar.insertBefore(appearance, topbar.firstChild);
    applyAppearance(document.documentElement.classList.contains(LIGHT));

    var home = nav.querySelector('[data-v13-view="today"]');
    if (home) {
      home.classList.add('cb-home');
      home.setAttribute('aria-label', 'Главная — сегодня');
    }

    var blocks = {};
    groups.forEach(function (group) {
      var wrap = document.createElement('div');
      wrap.className = 'cb-group';
      wrap.dataset.cbGroup = group.id;

      var button = document.createElement('button');
      button.type = 'button';
      button.className = 'cb-group-head';
      button.dataset.cbGroupToggle = group.id;
      button.setAttribute('aria-expanded', 'false');
      button.innerHTML = '<span></span><span class="cb-chevron" aria-hidden="true">›</span>';
      button.firstChild.textContent = group.label;

      var body = document.createElement('div');
      body.className = 'cb-group-body';
      body.id = 'cbGroupBody-' + group.id;
      button.setAttribute('aria-controls', body.id);
      wrap.appendChild(button);
      wrap.appendChild(body);
      blocks[group.id] = { wrapper: wrap, body: body, head: button };
      nav.appendChild(wrap);

      group.pages.forEach(function (page) {
        var original = nav.querySelector('[data-v13-view="' + page + '"]');
        if (!original) return;
        // v13-safe-subnav is generated by existing navigation code and must move
        // with its parent button, keeping its original click handlers intact.
        var next = original.nextElementSibling;
        body.appendChild(original);
        if (next && next.matches('.v13-safe-subnav[data-parent="' + page + '"]')) {
          body.appendChild(next);
        }
      });
    });

    var lastOpen = null;
    function setOpen(groupId) {
      lastOpen = groupId;
      groups.forEach(function (group) {
        var b = blocks[group.id];
        var open = group.id === groupId;
        if (b.wrapper.classList.contains('open') !== open) b.wrapper.classList.toggle('open', open);
        b.head.setAttribute('aria-expanded', String(open));
      });
    }
    function syncCurrent() {
      var active = nav.querySelector('[data-v13-view].active');
      var id = active && active.dataset.v13View;
      var owner = id && pageToGroup[id];
      groups.forEach(function (group) {
        var b = blocks[group.id];
        var isCurrent = owner === group.id;
        if (b.wrapper.classList.contains('current') !== isCurrent)
          b.wrapper.classList.toggle('current', isCurrent);
      });
      // A route change must make the selected page visible in the sidebar.
      if (owner && owner !== lastOpen) setOpen(owner);
      if (id === 'today') setOpen(null);
    }
    nav.addEventListener('click', function (event) {
      var heading = event.target.closest('[data-cb-group-toggle]');
      if (heading && nav.contains(heading)) {
        event.preventDefault();
        var id = heading.dataset.cbGroupToggle;
        setOpen(lastOpen === id ? null : id);
        return;
      }
      if (event.target.closest('[data-v13-view]')) {
        // Existing click listener handles routing. Only sync visual grouping.
        setTimeout(syncCurrent, 0);
      }
    });

    // Also follow route changes originating from other parts of the board.
    var observer = new MutationObserver(function () { syncCurrent(); });
    nav.querySelectorAll('[data-v13-view]').forEach(function (button) {
      observer.observe(button, {attributes:true,attributeFilter:['class']});
    });
    syncCurrent();
    document.documentElement.dataset.cbDesign = 'refined-v1';
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
